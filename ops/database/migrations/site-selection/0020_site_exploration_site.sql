  `status` TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '状态：1待勘探 2待补充 3已勘探 4已签约 5建设中 6建设完成 7运营中',
  `explorer_name` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '勘探人姓名',
  `exploration_team` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '勘探小组',
  `exploration_date` CHAR(10) NOT NULL DEFAULT '' COMMENT '勘探业务日期，格式YYYY-MM-DD',
