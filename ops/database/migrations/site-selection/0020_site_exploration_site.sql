  KEY `idx_site_exploration_updated` (`updated_at`, `id`),
  KEY `idx_site_exploration_status_updated` (`status`, `updated_at`, `id`),
  KEY `idx_site_exploration_team_updated` (`exploration_team`, `updated_at`, `id`),
  KEY `idx_site_exploration_city_updated` (`province_city`, `updated_at`, `id`),
  KEY `idx_site_exploration_project` (`project_name`, `id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='勘探站点';
